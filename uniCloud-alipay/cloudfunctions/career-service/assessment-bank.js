const likert = labels => labels.map((label, i) => ({ value: i + 1, label }))
const abilityOptions = labels => labels.map((label, i) => ({ value: 'ABCD'[i], label }))

function buildQuestions() {
  const out = []
  const add = (code, rows, mapper) => rows.forEach((row, i) => out.push({
    ...mapper(row), test_code: code,
    question_id: `${code}_${String(i + 1).padStart(3, '0')}`,
    sort: i + 1, difficulty: 'basic', status: 1,
    version: 1, created_at: Date.now()
  }))

  add('mbti', mbtiRaw, r => ({
    title: r[2], question: r[2], dimension: r[0], polarity: r[1],
    options: likert(['非常不符合','比较不符合','不确定','比较符合','非常符合']),
    scoring: 'likert_preference'
  }))
  add('holland', hollandRaw, r => ({
    title: r[1], question: r[1], dimension: r[0],
    options: likert(['完全不感兴趣','不太感兴趣','一般','比较感兴趣','非常感兴趣']),
    scoring: 'likert_interest'
  }))
  add('ability', abilityRaw, r => ({
    title: r[1], question: r[1], dimension: r[0],
    options: abilityOptions(r[2]), correct_answer: r[3],
    explanation: r[4], scoring: 'objective'
  }))
  add('value', valueRaw, r => ({
    title: r[1], question: r[1], dimension: r[0],
    options: likert(['完全不重要','不太重要','一般','比较重要','非常重要']),
    scoring: 'likert_value'
  }))
  return out
}

